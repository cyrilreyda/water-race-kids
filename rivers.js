// Проєкція: рівнопроміжна з поправкою на широту, 26 пікселів на градус широти
const MAP_W = 316, MAP_H = 216;
const mapXY = ([lon, lat]) => [((lon - 22) * 0.663 * 26).toFixed(1), ((52.6 - lat) * 26).toFixed(1)];
const mapPts = pts => pts.map(p=>mapXY(p).join(',')).join(' ');

// Схема: Україна, море, усі ріки трас тонкою лінією, обрана — товстою, її міста й Київ для орієнтиру.
// Коротка річка (view — [довгота лівого краю, широта верхнього, ширина в градусах]) показана збільшено,
// а в кутку — маленька Україна з рамкою, де цей шматок
function riverMap(id){
  const r = RIVERS[id];
  let vx = 0, vy = 0, vw = MAP_W, vh = MAP_H;
  if(r.view){ [vx, vy] = mapXY([r.view[0], r.view[1]]).map(Number); vw = r.view[2] * 0.663 * 26; vh = vw * MAP_H / MAP_W; }
  const s = vw / MAP_W;   // у збільшеній схемі товщини ліній і шрифт менші в тій самій пропорції
  const land = (sea, line) => `<polygon points="${mapPts(MAP_SEA)}" fill="${sea}"/><polygon points="${mapPts(MAP_AZOV)}" fill="${sea}"/>
    <polygon points="${mapPts(MAP_UA)}" fill="#FFF6D8" stroke="#C9B98E" stroke-width="${line}" stroke-linejoin="round"/>`;
  const thin = Object.values(RIVERS).filter(x=>x.line && x !== r).map(x=>`<polyline points="${mapPts(x.line)}" fill="none" stroke="#9CC8E8" stroke-width="${1.2*s}" stroke-linejoin="round"/>`).join('');
  const main = r.line ? (r.extra || []).map(l=>`<polyline points="${mapPts(l)}" fill="none" stroke="#7FB6E0" stroke-width="${1.8*s}" stroke-linejoin="round"/>`).join('') +
    `<polyline points="${mapPts(r.line)}" fill="none" stroke="#1E78C8" stroke-width="${3.2*s}" stroke-linecap="round" stroke-linejoin="round"/>` : '';
  const names = [...new Set([...(r.view ? [] : ['Київ']), ...r.cities])];
  const dots = names.map(n=>{
    const [lon, lat, left] = MAP_CITIES[n], [x, y] = mapXY([lon, lat]).map(Number);
    const dot = n === 'Київ' ? `<circle cx="${x}" cy="${y}" r="${4*s}" fill="#E8453C" stroke="#fff" stroke-width="${1.5*s}"/>` : `<circle cx="${x}" cy="${y}" r="${2.8*s}" fill="#1B1B3A" stroke="#fff" stroke-width="${1.2*s}"/>`;
    return dot + `<text x="${x + (left ? -5 : 5)*s}" y="${y + 3.5*s}" text-anchor="${left ? 'end' : 'start'}">${n}</text>`;
  }).join('');
  const inset = r.view ? `<g transform="translate(${vx + 3*s} ${vy + 3*s}) scale(${.24*s})">
      <rect width="${MAP_W}" height="${MAP_H}" fill="#F4F8FB" stroke="#9AA3B5" stroke-width="3"/>${land('#CFE8F7', 2)}
      <rect x="${vx}" y="${vy}" width="${vw}" height="${vh}" fill="none" stroke="#E8453C" stroke-width="5"/></g>` : '';
  return `<svg class="river-map" viewBox="${vx} ${vy} ${vw.toFixed(1)} ${vh.toFixed(1)}" role="img" aria-label="Схема: ${r.name} на карті України">
    <rect x="${vx}" y="${vy}" width="${vw}" height="${vh}" fill="#F4F8FB"/>
    ${land(r.sea ? '#7DC0EA' : '#CFE8F7', 1.2*s)}
    ${thin}${main}
    ${r.sea ? `<text x="${mapXY([31.4, 44.95])[0]}" y="${mapXY([31.4, 44.95])[1]}" class="sea-name">Чорне море</text>` : ''}
    ${(r.labels || []).map(([t, lon, lat])=>`<text x="${mapXY([lon, lat])[0]}" y="${mapXY([lon, lat])[1]}" class="sea-name" style="font-size:${10*s}px">${t}</text>`).join('')}
    <g class="cities" style="font-size:${9*s}px; stroke-width:${3*s}px">${dots}</g>${inset}</svg>`;
}

